# Pros and Cons of libraries

# We want to be careful with packages because it's not always good to use them.
# Well, these packages are created by developers and programmers. You can have people that are creating really, really good packages, but also people that are creating bad packages that my be buggy and don't work well.

# So you have to develop that skill to make sure you're able to see, hey, this package is really popular or this package is being maintained or this library is really popular with the commnunity, So most likely it's a good package to use

# Also keep in mind that every time we add a library to our project, we are adding more and more code, which means more and more bytes of data so our project gets heavier and heavier and heavier.
# So that's also something that you want to consider before you're importing a library, ask yourself this could I just write this myself?

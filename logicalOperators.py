# LOGICAL OPERATORS (<, >, ==, <=, >=, !=, not)

print(4 > 5)
print(5 == 5)

print("gibson" == "gibson")

print("a" > "b")  # False
print("c" > "b")  # True

print("gibson" != "joseph")
print(100 != 100)

# NOT
print(
    "Not true: ", not (False)
)  # we can also write this code without the brackets: not True
print(not True)

print("not 1 == 1", not 1 == 1)

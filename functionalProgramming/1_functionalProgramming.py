# Functional Programming
# A paradigm is way for us to think about our code and organize our code.
# Now some of the concepts are different than object oriented programming, but that doesn't mean that you have to pick one or other or one is better than the other. Instead, we can use the concepts from both to think like programmers and understand that there's tradeoffs, pros and cons to each.


# What is functional programming?
# Functional prgramming is all about separation of concerns, which object oriented programming does as well.
# Its all about packaging our code into separate chunks so that everything's well organized in each part of our code. And each part is organized in a way that makes sense based on functionality.
# So when we say separation of concerns, we mean each part concerns itself with one thing that it's good at.

# In our boject oriented programming section how we had two classes to divide up attributes and methods of, let's say, a wizard class and an archer class. And functional programming has this idea as well of separating concerns, but they also separate data and functions. That's how a functional programmer views the world. Instead of combining methods and attributes, we separate them up because there are two separate things, there's data and data gets interacted and acted upon.

# In functional programming, we're not going to combine both data and functions as one piece in an object like we saw with object oriented programming.

# Now there is no correct definition for what is and isn't functional. But generally functional languages have and emphasis on simplicity, where data and functions are concerned, because in most functional programming paradigms we don't hae this idea of class and objects. Instead, functions operate on well defined data structures like lists and dictionaries that we saw rather than belonging that data structure to an object.

# But at the end of the day, the goal of a functional programming paradigm is the same as object oriented paradigm.

# It's the idea of making our code;
# 1. Clear + Understandable
# 2. Easy to Extend (We can grow our code and make it better and better and have others come and extend our code.)
# 3. Easy to maintain
# 4. Memory Efficient (Keeping our code memory efficient, because we're not storing information all over the place)
# 5. DRY (It keeps our code DRY, so that we are not repeating ourselves.)

